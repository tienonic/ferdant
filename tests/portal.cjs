const assert = require('node:assert/strict');

module.exports = async function checkPortal(page) {
 await page.waitForFunction(()=>document.querySelector('#city-map').dataset.ready==='true');
 assert.equal(await page.locator('#location-start #city-map').count(),1);
 assert.equal(await page.locator('#location-start [data-city-download]').count(),0);
 const tabs=page.getByRole('tab');
 assert.equal(await tabs.count(),3);
 assert.equal(await page.getByRole('tabpanel').count(),1);
 assert(await page.locator('#california-resources').isVisible());
 assert.equal(await page.locator('.state-resource').count(),4);
 assert.equal(await page.locator('.phone-directory[open]').count(),0);
 await page.locator('.phone-toggle').click();
 assert(await page.locator('.phone-table').isVisible());
 await page.locator('.phone-toggle').click();
 await tabs.first().focus();await page.keyboard.press('ArrowRight');
 assert(await page.locator('#tools').isVisible());
 assert.equal(await page.locator(':focus').getAttribute('id'),'tab-guides');
 const launcher=page.locator('.portal-tools [data-open-tool="compare-bill"]');
 await launcher.click();
 assert(await page.getByRole('dialog',{name:'Compare a bill',exact:true}).isVisible());
 await page.getByLabel('Previous bill ($)').fill('60');await page.getByLabel('Current bill ($)').fill('75');
 await page.getByRole('button',{name:'Compare the totals'}).click();
 assert((await page.locator('#bill-result').innerText()).includes('$15.00 (25.0%) higher'));
 await page.keyboard.press('Escape');assert(await launcher.evaluate(el=>el===document.activeElement));
 await page.getByRole('link',{name:'Cost over time On this page',exact:false}).click();
 assert(await page.getByLabel('Monthly cost (USD)',{exact:true}).isVisible());
 await tabs.nth(1).focus();await page.keyboard.press('End');
 assert(await page.locator('#communities').isVisible());
 assert.equal(await page.locator('.community-resource').count(),5);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.keyboard.press('Home');assert(await page.locator('#california-resources').isVisible());
 await page.getByRole('tab',{name:'Guides & tools'}).click();
 await page.getByRole('tab',{name:'Communities',exact:true}).click();
 await page.goBack();assert(await page.locator('#tools').isVisible());
 await page.goto(new URL('/#who-can-fix-this',page.url()).href);
 assert(await page.locator('#tools').isVisible());
 assert(await page.locator('#who-can-fix-this').evaluate(el=>el.open));
 await page.locator('#who-can-fix-this .portal-destination').first().focus();
 assert(await page.locator(':focus').evaluate(el=>parseFloat(getComputedStyle(el).outlineWidth)>=3));
 await page.goto(new URL('/',page.url()).href);
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:`screenshots/landing-flow-${page.viewportSize().width}.png`,fullPage:true});
 assert(await page.evaluate(()=>localStorage.length===0&&sessionStorage.length===0));
};
